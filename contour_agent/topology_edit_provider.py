_EDITOR_TAGS = {"micro_segment", "collinear_support", "cocircular_support", "continuity",
                "annotation_target", "primitive_count", "hatching_interference", "source_boundary"}
_EVALUATOR_TAGS = {"source_boundary", "continuity", "primitive_count", "annotation_support",
                   "local_residual", "local_validity"}
_CONFIDENCE = {"low", "medium", "high", "abstain"}


def _radius_detail_payload(image_path, overlay_path, record):
    """Build a source/overlay detail pair around one observed radius leader."""
    leader = record.get("leader") or {}
    target = leader.get("target_source_px")
    box = record.get("source_box")
    if not target or not box:
        return None
    with Image.open(image_path) as source_loaded, Image.open(overlay_path) as overlay_loaded:
        source = source_loaded.convert("RGB")
        overlay = overlay_loaded.convert("RGB")
        points = [tuple(map(float, point)) for point in box] + [tuple(map(float, target))]
        xs, ys = [point[0] for point in points], [point[1] for point in points]
        pad = max(70., min(source.size) * .045)
        bounds = (max(0., min(xs) - pad), max(0., min(ys) - pad),
                  min(float(source.width), max(xs) + pad), min(float(source.height), max(ys) + pad))
        if bounds[2] - bounds[0] < 16 or bounds[3] - bounds[1] < 16:
            return None
        source_crop = source.crop(tuple(map(int, bounds)))
        sx, sy = overlay.width / source.width, overlay.height / source.height
        overlay_bounds = (int(bounds[0] * sx), int(bounds[1] * sy),
                          int(bounds[2] * sx), int(bounds[3] * sy))
        overlay_crop = overlay.crop(overlay_bounds).resize(source_crop.size, Image.Resampling.LANCZOS)
        width = min(1100, max(source_crop.width, 480))
        scale = width / source_crop.width
        size = (width, max(1, round(source_crop.height * scale)))
        source_crop = source_crop.resize(size, Image.Resampling.LANCZOS)
        overlay_crop = overlay_crop.resize(size, Image.Resampling.LANCZOS)
        canvas = Image.new("RGB", (width, size[1] * 2 + 6), "white")
        canvas.paste(source_crop, (0, 0)); canvas.paste(overlay_crop, (0, size[1] + 6))
        ImageDraw.Draw(canvas).rectangle((0, size[1], width, size[1] + 5), fill=(25, 90, 84))
        output = BytesIO(); canvas.save(output, format="JPEG", quality=88, optimize=True)
        encoded = output.getvalue()
    if len(encoded) > 2 * 1024 * 1024:
        return None
    return "data:image/jpeg;base64," + base64.b64encode(encoded).decode("ascii"), {
        "kind": "radius_detail", "record_id": record.get("record_id"),
        "input_image_sha256": hashlib.sha256(encoded).hexdigest(),
        "input_image_size": list(canvas.size), "input_image_bytes": len(encoded),
        "ground_truth_used": False,
    }


def _rank_radius_detail_records(annotation_inventory, graph, *, limit=6):
    """Prioritize distinct, locally supported radius targets for multimodal review."""
    supports = [row for row in graph.get("annotation_support", []) if isinstance(row, dict)
                and row.get("kind") == "radius" and row.get("status") == "candidate_supported"]
    support_by_record = {row.get("record_id"): row for row in supports if row.get("record_id")}
    support_count_by_entity = {}
    for row in supports:
        entity_id = row.get("candidate_entity_id")
        if entity_id:
            support_count_by_entity[entity_id] = support_count_by_entity.get(entity_id, 0) + 1
    entities = {row.get("id"): row for row in graph.get("entities", []) if isinstance(row, dict)}
    ranked = []
    for position, record in enumerate(annotation_inventory):
        if not isinstance(record, dict) or record.get("kind") != "radius" or not record.get("leader"):
            continue
        support = support_by_record.get(record.get("record_id"))
        entity_id = support.get("candidate_entity_id") if support else None
        entity = entities.get(entity_id, {})
        nominal = record.get("nominal")
        fitted = entity.get("radius")
        mismatch = 0.0
        if (graph.get("units") == "mm" and isinstance(nominal, (int, float)) and nominal > 0
                and isinstance(fitted, (int, float)) and fitted > 0):
            mismatch = abs(float(math.log(float(fitted) / float(nominal))))
        uniqueness = entity_id is not None and support_count_by_entity.get(entity_id) == 1
        primitive_conflict = entity.get("type") == "LINE"
        arrow = bool(support and support.get("arrowhead_verified"))
        gap = float(support.get("target_gap_px", 1e9)) if support else 1e9
        # Review distinct targets first.  Within those, type conflicts and
        # large radius disagreement deserve the most visual attention.
        key = (bool(support), uniqueness, primitive_conflict, mismatch, arrow, -gap, -position)
        ranked.append((key, position, record, entity_id))
    ranked.sort(key=lambda row: row[0], reverse=True)
    selected, seen_entities = [], set()
    for _, position, record, entity_id in ranked:
        if entity_id and entity_id in seen_entities:
            continue
        selected.append((position, record, entity_id))
        if entity_id:
            seen_entities.add(entity_id)
        if len(selected) >= limit:
            break
    return selected


def _safe_receipt(receipt, settings):
    def clean(value):
        if isinstance(value, str):
            if settings.api_key:
                value = value.replace(settings.api_key, "[REDACTED]")
            value = re.sub(r"\bsk-[A-Za-z0-9_-]+", "[REDACTED]", value)
            return re.sub(r"\bBearer\s+[A-Za-z0-9._~+/=-]+", "Bearer [REDACTED]", value, flags=re.I)
        if isinstance(value, dict):
            return {key: clean(item) for key, item in value.items()}
        if isinstance(value, list):
            return [clean(item) for item in value]
        return value
    result = clean(receipt)
    if "response_excerpt" in result:
        result["response_excerpt"] = result["response_excerpt"][:1200]
    return result


def _consecutive(entity_ids, graph):
    entities = graph.get("entities", []) if isinstance(graph, dict) else []
    ids = [row.get("id") for row in entities if isinstance(row, dict)]
    if len(ids) != len(entities) or not entity_ids or entity_ids[0] not in ids:
        return False
    start = ids.index(entity_ids[0])
    return entity_ids == [ids[(start + offset) % len(ids)] for offset in range(len(entity_ids))]


def validate_edit_response(text, graph, record_ids):
    if not isinstance(text, str) or len(text) > 16000:
        raise _InspectionError("invalid_output")
    try:
        value = _single_json_object(text.strip())
    except (TypeError, ValueError):
        raise _InspectionError("invalid_json") from None
    if not isinstance(value, dict) or set(value) != {"observation", "operations", "confidence"}:
        raise _InspectionError("schema_mismatch")
    if not isinstance(value["observation"], str) or len(value["observation"]) > 200:
        raise _InspectionError("invalid_observation")
    if value["confidence"] not in _CONFIDENCE:
        raise _InspectionError("invalid_confidence")
    operations = value["operations"]
    if not isinstance(operations, list) or len(operations) > 5:
        raise _InspectionError("invalid_operations")
    known_entities = {row.get("id") for row in graph.get("entities", []) if isinstance(row, dict)}
    for operation in operations:
        if not isinstance(operation, dict) or set(operation) != {"action", "entity_ids", "record_id", "evidence_tags"}:
            raise _InspectionError("invalid_operations")
        ids = operation["entity_ids"]
        minimum = 1 if operation["action"] == "refit_chain_as_annotated_arc" else 2
        if (operation["action"] not in EDIT_ACTIONS or not isinstance(ids, list) or not minimum <= len(ids) <= 8
                or len(set(ids)) != len(ids) or not set(ids).issubset(known_entities) or not _consecutive(ids, graph)):
            raise _InspectionError("invalid_operations")
        if operation["record_id"] is not None and operation["record_id"] not in record_ids:
            raise _InspectionError("unknown_record_id")
        if operation["action"] == "refit_chain_as_annotated_arc" and operation["record_id"] is None:
            raise _InspectionError("annotated_arc_requires_record_id")
        tags = operation["evidence_tags"]
        if not isinstance(tags, list) or len(tags) > 8 or len(set(tags)) != len(tags) or not set(tags).issubset(_EDITOR_TAGS):
            raise _InspectionError("invalid_evidence_tags")
    if not operations and value["confidence"] != "abstain":
        raise _InspectionError("empty_operations_require_abstention")
    if operations and value["confidence"] == "abstain":
        raise _InspectionError("operations_conflict_with_abstention")
    return value


def validate_evaluation_response(text, allowed_ids, base_id):
    if not isinstance(text, str) or len(text) > 12000:
        raise _InspectionError("invalid_output")
    try:
        value = _single_json_object(text.strip())
    except (TypeError, ValueError):
        raise _InspectionError("invalid_json") from None
    required = {"candidate_id", "observation", "decision", "evidence_tags", "confidence"}
    if not isinstance(value, dict) or set(value) != required:
        raise _InspectionError("schema_mismatch")
    if not isinstance(value["observation"], str) or len(value["observation"]) > 200:
        raise _InspectionError("invalid_observation")
    tags = value["evidence_tags"]
    if not isinstance(tags, list) or len(tags) > 8 or len(set(tags)) != len(tags) or not set(tags).issubset(_EVALUATOR_TAGS):
        raise _InspectionError("invalid_evidence_tags")
    if value["confidence"] not in _CONFIDENCE or value["decision"] not in {"accept_edit", "preserve_base", "abstain"}:
        raise _InspectionError("invalid_decision")
    candidate_id = value["candidate_id"]
    if value["decision"] == "abstain":
        if candidate_id is not None or value["confidence"] != "abstain":
            raise _InspectionError("invalid_abstention")
    else:
        if candidate_id not in allowed_ids or value["confidence"] == "abstain":
            raise _InspectionError("unknown_candidate_id")
        if value["decision"] == "preserve_base" and candidate_id != base_id:
            raise _InspectionError("preserve_base_id_mismatch")
        if value["decision"] == "accept_edit" and candidate_id == base_id:
            raise _InspectionError("accept_edit_id_mismatch")
    return value


class TopologyEditProvider:
    def __init__(self, settings):
        self.settings = settings

    def propose(self, image_path, overlay_path, candidate, annotation_inventory):
        return asyncio.run(self._propose(image_path, overlay_path, candidate, annotation_inventory))

    async def _propose(self, image_path, overlay_path, candidate, annotation_inventory):
        settings, started = self.settings, time.monotonic()
        graph = candidate.get("graph") if isinstance(candidate, dict) else None
        graph = graph if isinstance(graph, dict) else {}
        record_ids = {row.get("record_id") for row in annotation_inventory if isinstance(row, dict) and row.get("record_id")}
        receipt = {"status": "failed", "protocol": settings.wire_api+"-local-topology-edit-v1",
                   "model": settings.model, "network_requests": 0, "http_success": False,
                   "schema_success": False, "image_sent": False, "ground_truth_sent": False,
                   "coordinates_sent": False, "operations": [], "observation": "", "confidence": "abstain"}
        def finish():
            receipt["elapsed_seconds"] = round(time.monotonic()-started, 3)
            return _safe_receipt(receipt, settings)
        if not graph.get("entities"):
            receipt.update(status="skipped", error_code="missing_candidate_graph")
            return finish()
        if not settings.api_key:
            receipt.update(status="not_configured", error_code="not_configured")
            return finish()
        if not endpoint_allowed(settings):
            receipt["error_code"] = "invalid_endpoint"
            return finish()
        try:
            images, metadata = [], []
            for kind, path in (("source", image_path), ("selected_topology", overlay_path)):
                encoded, meta = _image_payload(Path(path))
                images.append({"type": "image_url", "image_url": {"url": encoded}})
                metadata.append({"kind": kind, **meta})
            detail_order = []
            for _, record, entity_id in _rank_radius_detail_records(annotation_inventory, graph):
                detail = _radius_detail_payload(Path(image_path), Path(overlay_path), record)
                if detail is None:
                    continue
                encoded, meta = detail
                images.append({"type": "image_url", "image_url": {"url": encoded}})
                metadata.append(meta)
                detail_order.append({"image_index": len(images), "record_id": record.get("record_id"),
                                     "candidate_entity_id": entity_id})
            entity_ids = [row.get("id") for row in graph.get("entities", [])]
            records = [{key: row.get(key) for key in ("record_id", "text", "kind", "nominal", "leader_status")}
                       for row in annotation_inventory if isinstance(row, dict) and row.get("record_id")][:48]
            annotation_support = [{key: row.get(key) for key in ("record_id", "text", "kind", "nominal",
                                                                  "candidate_entity_id", "candidate_entity_type",
                                                                  "target_gap_px", "arrowhead_verified", "status")}
                                  for row in graph.get("annotation_support", []) if isinstance(row, dict)]
            protected = sorted({row.get("candidate_entity_id") for row in annotation_support
                                if row.get("kind") == "radius" and row.get("status") == "candidate_supported"
                                and row.get("candidate_entity_id")})
            packet = {"candidate_id": candidate.get("id"), "ordered_entity_ids": entity_ids,
                      "entity_types": {row.get("id"): row.get("type") for row in graph.get("entities", [])},
                      "annotation_records": records, "entity_annotation_support": annotation_support,
                      "protected_radius_entities": protected, "radius_detail_order": detail_order}
            packet_text = json.dumps(packet, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
            payload = {"model": settings.model, "temperature": 0, "max_tokens": 1200,
                       "messages": [{"role": "system", "content": EDITOR_PROMPT},
                                    {"role": "user", "content": [{"type": "text", "text": packet_text}, *images]}]}
            endpoint, wire_payload = prepare_request(settings, payload)
            budget = min(600., max(.001, float(settings.api_timeout)))
            async with httpx.AsyncClient(timeout=httpx.Timeout(budget, connect=min(10., budget)),
                                         trust_env=settings.trust_env, verify=True, follow_redirects=False) as client:
                receipt["network_requests"] = 1
                response = await client.post(endpoint, headers=request_headers(settings), json=wire_payload)
            receipt.update(http_status=response.status_code, http_success=response.status_code == 200,
                           image_sent=True, input_images=metadata)
            if response.status_code != 200:
                receipt["error_code"] = "http_error"
                return finish()
            text, source, reason, _ = extract_text(settings, response)
            value = validate_edit_response(text, graph, record_ids)
            receipt.update(status="succeeded", schema_success=True, response_text_source=source,
                           finish_reason=reason, response_text_sha256=hashlib.sha256(text.encode()).hexdigest(),
                           response_excerpt=text[:1200], **value)
            return finish()
        except (_InspectionError, ValueError, TypeError, KeyError, json.JSONDecodeError) as error:
            receipt["error_code"] = error.code if isinstance(error, _InspectionError) else "invalid_response"
            return finish()
        except (httpx.TimeoutException, httpx.RequestError):
            receipt["error_code"] = "transport_error"
            return finish()


class TopologyEvaluationProvider:
    def __init__(self, settings):
        self.settings = settings

    def select(self, image_path, candidates, base_id, annotation_inventory=None):
        return asyncio.run(self._select(image_path, candidates, base_id, annotation_inventory or []))

    async def _select(self, image_path, candidates, base_id, annotation_inventory):
        settings, started = self.settings, time.monotonic()
        local = evaluate_candidates(candidates, max_candidates=5)
        allowed = set(local["bounded_candidate_ids"])
        receipt = {"status": "failed", "protocol": settings.wire_api+"-topology-edit-evaluation-v1",
                   "model": settings.model, "network_requests": 0, "http_success": False,
                   "schema_success": False, "image_sent": False, "ground_truth_sent": False,
                   "coordinates_sent": False, "selected_candidate_id": None, "observation": "",
                   "decision": "abstain", "evidence_tags": [], "confidence": "abstain",
                   "local_evaluation": local}
        def finish():
            receipt["elapsed_seconds"] = round(time.monotonic()-started, 3)
            return _safe_receipt(receipt, settings)
        if base_id not in allowed or len(allowed) < 2:
            receipt.update(status="skipped", error_code="insufficient_admissible_edit_candidates")
            return finish()
        if not settings.api_key:
            receipt.update(status="not_configured", error_code="not_configured")
            return finish()
        if not endpoint_allowed(settings):
            receipt["error_code"] = "invalid_endpoint"
            return finish()
        by_id = {row.get("id"): row for row in candidates if isinstance(row, dict)}
        try:
            source_payload, source_meta = _image_payload(Path(image_path))
            images = [{"type": "image_url", "image_url": {"url": source_payload}}]
            metadata = [{"kind": "source", **source_meta}]
            for candidate_id in local["bounded_candidate_ids"]:
                payload, meta = _image_payload(Path(by_id[candidate_id]["overlay_path"]))
                images.append({"type": "image_url", "image_url": {"url": payload}})
                metadata.append({"kind": "candidate", "candidate_id": candidate_id, **meta})
            candidate_image_order = [{"image_index": index + 2, "candidate_id": candidate_id}
                                     for index, candidate_id in enumerate(local["bounded_candidate_ids"])]
            radius_detail_order = []
            base = by_id[base_id]
            for _, record, entity_id in _rank_radius_detail_records(
                    annotation_inventory, base.get("graph") or {}, limit=4):
                detail = _radius_detail_payload(
                    Path(image_path), Path(base["overlay_path"]), record)
                if detail is None:
                    continue
                payload, meta = detail
                images.append({"type": "image_url", "image_url": {"url": payload}})
                metadata.append(meta)
                radius_detail_order.append({"image_index": len(images),
                                            "record_id": record.get("record_id"),
                                            "candidate_entity_id": entity_id})
            packet = {"base_candidate_id": base_id, "candidate_order": local["bounded_candidate_ids"],
                      "candidate_image_order": candidate_image_order,
                      "radius_detail_order": radius_detail_order,
                      "candidates": local["bounded_candidates"]}
            packet_text = json.dumps(packet, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
            payload = {"model": settings.model, "temperature": 0, "max_tokens": 800,
                       "messages": [{"role": "system", "content": EVALUATOR_PROMPT},
                                    {"role": "user", "content": [{"type": "text", "text": packet_text}, *images]}]}
            endpoint, wire_payload = prepare_request(settings, payload)
            budget = min(600., max(.001, float(settings.api_timeout)))
            async with httpx.AsyncClient(timeout=httpx.Timeout(budget, connect=min(10., budget)),
                                         trust_env=settings.trust_env, verify=True, follow_redirects=False) as client:
                receipt["network_requests"] = 1
                response = await client.post(endpoint, headers=request_headers(settings), json=wire_payload)
            receipt.update(http_status=response.status_code, http_success=response.status_code == 200,
                           image_sent=True, input_images=metadata)
            if response.status_code != 200:
                receipt["error_code"] = "http_error"
                return finish()
            text, source, reason, _ = extract_text(settings, response)
            value = validate_evaluation_response(text, allowed, base_id)
            receipt.update(status="succeeded", schema_success=True,
                           selected_candidate_id=value["candidate_id"], response_text_source=source,
                           finish_reason=reason, response_text_sha256=hashlib.sha256(text.encode()).hexdigest(),
                           response_excerpt=text[:1200], **{key: value[key] for key in value if key != "candidate_id"})
            return finish()
        except (_InspectionError, ValueError, TypeError, KeyError, json.JSONDecodeError) as error:
            receipt["error_code"] = error.code if isinstance(error, _InspectionError) else "invalid_response"
            return finish()
        except (httpx.TimeoutException, httpx.RequestError):
            receipt["error_code"] = "transport_error"
            return finish()
